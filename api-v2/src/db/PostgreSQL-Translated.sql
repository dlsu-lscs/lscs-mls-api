CREATE TABLE IF NOT EXISTS courses (
    cid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_name VARCHAR(120) NOT NULL,
    section VARCHAR(30) NOT NULL,
    remarks VARCHAR(255),
    modality VARCHAR(80) DEFAULT '',
    term VARCHAR(80) DEFAULT '',
    campus VARCHAR(80) DEFAULT ''
); 

CREATE TABLE IF NOT EXISTS course_timeslots (
    tid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day VARCHAR(5) NOT NULL,
    time VARCHAR(20) NOT NULL,
    room VARCHAR(20),
    instructor VARCHAR(120),
    course_id INTEGER NOT NULL,
    FOREIGN KEY (course_id)
        REFERENCES courses(cid)
        ON DELETE CASCADE
); 

CREATE TABLE IF NOT EXISTS course_enrollments (
    eid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enroll_cap INTEGER,
    enrolled INTEGER,
    course_id INTEGER NOT NULL,
    FOREIGN KEY (course_id)
        REFERENCES courses(cid)
        ON DELETE CASCADE
); 

CREATE TABLE IF NOT EXISTS users (
    uid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100),
    given_name VARCHAR(80),
    family_name VARCHAR(80),
    user_id VARCHAR(50) UNIQUE NOT NULL,
    picture_url VARCHAR(120)
); 



CREATE TABLE IF NOT EXISTS selected_courses (
    sid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    FOREIGN KEY (course_id)
        REFERENCES courses(cid)
        ON DELETE CASCADE,
    FOREIGN KEY (user_id)
        REFERENCES users(uid)
        ON DELETE CASCADE
);




