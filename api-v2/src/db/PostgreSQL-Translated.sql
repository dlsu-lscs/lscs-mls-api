CREATE TABLE IF NOT EXISTS courses (
    cid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_name VARCHAR(120) NOT NULL,
    section VARCHAR(30) NOT NULL,
    remarks VARCHAR(255),
    modality VARCHAR(80) DEFAULT '',
    term VARCHAR(80) DEFAULT '',
    campus VARCHAR(80) DEFAULT ''
); 

CREATE TABLE IF NOT EXISTS course_timeslots (
    tid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day VARCHAR(5) NOT NULL,
    time VARCHAR(20) NOT NULL,
    room VARCHAR(20),
    instructor VARCHAR(120),
    course_id INTEGER NOT NULL,
    FOREIGN KEY (course_id)
        REFERENCES courses(cid)
        ON DELETE CASCADE
);


